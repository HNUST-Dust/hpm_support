/* ecat hwardware init */
hpm_stat_t ecat_hardware_init(const struct device *esc_dev)
{
    hpm_stat_t stat;
    int eeprom_status;

#if defined(ESC_EEPROM_EMULATION) && ESC_EEPROM_EMULATION
    stat = ecat_flash_eeprom_init();
    if (stat != status_success) {
        printk("Flash simulation EEPROM initialization failed.\n");
        return stat;
    }

    hpm_esc_configure_eeprom(esc_dev, true, false);

    /* eeprom reload */
    ecat_eeprom_emulation_reload_response();

#else

    stat = esc_eeprom_content_init(); /* I2C init EEPROM context */
    if (stat != status_success) {
        printk("I2C initialize actual EEPROM content failed.\n");
        return stat;
    }

    init_esc_eeprom_pin(); /* config ESC pin for EEPROM */

    hpm_esc_configure_eeprom(esc_dev, false, ECAT_EEPROM_SIZE_BYTE > 256);
#endif


    /* Wait Loading ESC EEPROM and check */
    eeprom_status = hpm_esc_check_eeprom(esc_dev);
    if (eeprom_status != 0) {
        if (eeprom_status == -EBADMSG) {
            printk("EEPROM loading with checksum error.\n");
            printk("EtherCAT communication is possible even if the EEPROM is blank(checksum error), please update eeprom context.\n");
            /* not return */
        } else {
            printk("EEPROM loading failed, please check EEPROM setting.\n");
            return status_fail;
        }
    } else {
        printk("EEPROM loading successful, no checksum error.\n");
    }

    /* PHY reset */
    ecat_phy_reset(esc_dev);

    /* Set PHY OFFSET */
    hpm_esc_configure_phy(esc_dev);

    /* Identify the board's Port0 PHY over ESC MDIO. */
    stat = ecat_phy_config(esc_dev);
    if (stat != status_success) {
        printk("PHY configuration failed.\n");
        return stat;
    }

    hpm_esc_configure_signals(esc_dev);

    if (status_success == stat) {
#if defined(ECAT_SSC_TIMER_USE_RTOS_TICK) && ECAT_SSC_TIMER_USE_RTOS_TICK
        ecat_time_init_rtos();
#else
        /* Open Timer driver */
        ecat_timer_ms_enable();
#endif /* ECAT_SSC_TIMER_USE_RTOS_TICK */

        /* Initialize the EtherCAT Slave Interface of the SSC */
        HW_Init();

    } else {
        /* Close operation */
    }

    return stat;
}

